import type { CollectionId } from './collections'

export type StayType =
  | 'Dome'
  | 'Mirror house'
  | 'A-frame'
  | 'Villa'
  | 'Loft'
  | 'Floating house'
  | 'Stilt house'
  | 'Treehouse'

export type Amenity = 'sauna' | 'hot-tub' | 'fireplace' | 'pool' | 'workspace' | 'ev-charger'

/** An interior or material close-up, shown beside the stay in the collections showcase. */
export interface StayDetail {
  image: string
  alt: string
  caption: string
}

export interface Stay {
  id: string
  index: string
  name: string
  type: StayType
  location: string
  country: string
  /** ISO 3166 alpha-2, shown as a badge in destination suggestions. */
  countryCode: string
  coordinates: string
  architect: string
  guests: number
  beds: number
  area: number
  pricePerNight: number
  image: string
  alt: string
  /** Where the house sits in `image` (CSS object-position), so wide crops keep it in frame. Default centre. */
  focus?: string
  detail?: StayDetail
  excerpt: string
  /** Landscape keywords matched by the destination search; the first two label the destination. */
  landscape: string[]
  petFriendly: boolean
  /** Out of 10, like the reviews in (06) Reflections. */
  rating: number
  reviews: number
  /** Bookable without a request to the host. */
  instantBook: boolean
  /** Runs on its own power and water. */
  offGrid: boolean
  amenities: Amenity[]
  /** ISO date the stay joined the catalogue (the "Newest" sort). */
  listed: string
  collections: CollectionId[]
  /** Mock booked periods, ISO [check-in, check-out) — half-open. */
  booked: [string, string][]
}

/** House grade, applied by the Unsplash CDN: muted, soft highlights, slightly warm. */
const GRADE = 'sat=-30&con=-10&high=-15&sepia=8'

/** Free Unsplash License photos only (`images.unsplash.com/photo-…`); Unsplash+ lives on another host. */
export const unsplash = (id: string, w = 1200) =>
  `https://images.unsplash.com/photo-${id}?w=${w}&q=80&auto=format&fit=crop&${GRADE}`

/**
 * An owned photo in `public/photos/`, shown as saved: the CDN can't apply `GRADE` to it, so grade the file itself if it should match.
 * One file serves every size; the `w=` parameter only keeps the components' `w=\d+` swaps working.
 */
export const ownPhoto = (file: string, w = 1200) => `/photos/${file}?w=${w}`

/** A square portrait cropped around the face (host avatars), in the same grade. */
export const portrait = (id: string, size = 240) => `${unsplash(id, size)}&h=${size}&crop=faces`

